// =============================================================================
//  SPARTAK :: data/DataSanitizer.h
//  Отсекает «нерегулярный» префикс потока баров.
//
//  Проблема: реальные XFBAR-файлы часто начинаются с Daily-баров, а потом
//  переходят в M5/M15/H1. Если стратегия начнёт работу с Daily-префикса,
//  фракталы и тренды будут построены на мусоре.
//
//  Решение: находим первый run из `confirm_bars` подряд идущих баров, где
//  Δt ≤ max_gap_ms, и стартуем оттуда.
//
//  Sanitizer НЕ хранит всю историю. Он потоково читает бары из BarStream,
//  считает интервалы и останавливается, как только подтвердит регулярность.
// =============================================================================
#pragma once
#include "core/Types.h"
#include "data/BarStream.h"
#include <cstdint>
namespace spartak::data {
// -----------------------------------------------------------------------------
// Отчёт о прогоне санитайзера.
// -----------------------------------------------------------------------------
struct SanitizeReport {
    bool    ok                      = false;  // удалось ли найти регулярный старт
    int64_t bars_scanned            = 0;      // сколько баров прочитано из потока
    int64_t bars_skipped            = 0;      // сколько из них пропущено (префикс)
    int64_t first_regular_timestamp = 0;      // Unix ms первого регулярного бара
    int64_t max_gap_seen_ms         = 0;      // максимальный Δt в префиксе
};
// -----------------------------------------------------------------------------
// DataSanitizer — stateless-утилита. Параметры задаются при создании.
// -----------------------------------------------------------------------------
class DataSanitizer {
public:
    // max_gap_ms     — порог «регулярности» Δt (по умолчанию 4 часа).
    // confirm_bars   — сколько подряд регулярных Δt подтверждают старт.
    explicit DataSanitizer(int64_t max_gap_ms   = 14'400'000LL,  // 4 часа
                           int     confirm_bars = 10);
    // Прогоняет поток до первого регулярного бара.
    // Поток смещается вперёд; пропущенные бары из него уходят.
    [[nodiscard]] SanitizeReport run(BarStream& stream) const;
    int64_t max_gap_ms()    const noexcept { return max_gap_ms_; }
    int     confirm_bars()  const noexcept { return confirm_bars_; }
private:
    int64_t max_gap_ms_;
    int     confirm_bars_;
};
} // namespace spartak::data